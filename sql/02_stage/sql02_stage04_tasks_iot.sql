-- Permiso para que SYSADMIN pueda ejecutar tasks
USE ROLE ACCOUNTADMIN;
GRANT EXECUTE TASK ON ACCOUNT TO ROLE SYSADMIN;

USE ROLE SYSADMIN;
USE DATABASE DWH_OLIST;
USE SCHEMA CONTROL;

-- Raiz: carga los archivos nuevos del stage a RAW (los ya cargados se omiten solos)
CREATE OR REPLACE TASK DWH_OLIST.CONTROL.T1_CARGAR_IOT
  WAREHOUSE = WH_CARGA
  SCHEDULE = '1440 MINUTE'
  COMMENT = 'Carga micro-lotes JSON del stage a RAW'
AS
COPY INTO DWH_OLIST.RAW.TELEMETRIA_IOT (payload, _archivo, _fila, _lote)
FROM (SELECT $1, METADATA$FILENAME, METADATA$FILE_ROW_NUMBER,
             REGEXP_SUBSTR(METADATA$FILENAME, 'L[0-9]{3}')
      FROM @DWH_OLIST.RAW.STG_IOT)
PATTERN = '.*telemetria_L[0-9]{3}_[0-9]{4}\\.json\\.gz'
FILE_FORMAT = (FORMAT_NAME = 'DWH_OLIST.RAW.FF_JSON_IOT')
ON_ERROR = 'ABORT_STATEMENT';

CREATE OR REPLACE TASK DWH_OLIST.CONTROL.T2_RAW_A_STAGE_IOT
  WAREHOUSE = WH_TRANSFORMACION
  COMMENT = 'Depura, aplana y clasifica lo nuevo de RAW hacia STAGE'
  AFTER DWH_OLIST.CONTROL.T1_CARGAR_IOT
AS
  CALL DWH_OLIST.CONTROL.SP_RAW_A_STAGE_IOT();

CREATE OR REPLACE TASK DWH_OLIST.CONTROL.T3_STAGE_A_CORE_IOT
  WAREHOUSE = WH_TRANSFORMACION
  COMMENT = 'MERGE incremental de STAGE hacia CORE'
  AFTER DWH_OLIST.CONTROL.T2_RAW_A_STAGE_IOT
AS
  CALL DWH_OLIST.CONTROL.SP_STAGE_A_CORE_IOT();

-- Se reanudan los hijos; la raiz se queda suspendida y se dispara con EXECUTE TASK
ALTER TASK DWH_OLIST.CONTROL.T3_STAGE_A_CORE_IOT RESUME;
ALTER TASK DWH_OLIST.CONTROL.T2_RAW_A_STAGE_IOT  RESUME;

SHOW TASKS IN SCHEMA DWH_OLIST.CONTROL;